def hbm():
    rows = []
    vend = open(f"{RAW}/phase2/xbutil_validate_mem-bw_41.txt").read()
    m = re.search(r"Throughput \(Type: HBM\) \(Bank count: (\d+)\) : ([\d.]+)MB/s", vend)
    macro("HbmVendorOneBank", float(m.group(2)) / 1000, "{:.1f}")
    for f in sorted(glob.glob(f"{RAW}/phase2/hbm_hbm1_*.json")):
        d = json.load(open(f))
        for mode in ("read", "write", "copy"):
            rs = [r for r in d["records"] if r["mode"] == mode and not r["spread"]]
            one = [r for r in rs if r["cus"] == 1][0]; full = max(rs, key=lambda r: r["cus"])
            rows.append(f"{d['cus']} CUs $\\times$ {d['width']}-bit & {mode} & {one['gbps_med']:.1f} & {full['cus']} & {full['gbps_med']:.1f} \\\\")
            tag = ("Thirtytwo" if d["cus"] == 32 else "Sixteen")
            macro(f"Hbm{tag}{mode.capitalize()}", full["gbps_med"], "{:.0f}")
            macro(f"Hbm{tag}PerCU{mode.capitalize()}", one["gbps_med"], "{:.1f}")
    write("tab_hbm.tex", "\n".join(rows) + "\n")
    if "HbmThirtytwoCopy" in MACROS:
        macro("HbmCeilingPct", 100 * float(MACROS["HbmThirtytwoCopy"]) / 460.0, "{:.0f}")


