# ------------------------------------------------------------------ functional suite + gate support
def suite():
    def ld(pat):
        f = sorted(glob.glob(f"{RAW}/phase4/{pat}"))
        return json.load(open(f[-1])) if f else None
    v07 = ld("v07_functional.json")
    sv = ld("sv_functional_sv_e16w512.json") or ld("sv_functional_sv_e16w.json") or ld("sv_functional_sv_e8.json")
    names = {"S1": "single-qubit gates (17 gates $\\times$ 5 positions)", "S2": "two-qubit gates (21 gates $\\times$ 12 ordered pairs)",
             "S3": "three- and more-qubit gates", "S4": "circuit families, $n=2$ to 20", "S5": "analytic large-$n$ checks"}
    rows = []
    for s in ("S1", "S2", "S3", "S4", "S5"):
        a = v07["summary"]["by_section"][s] if v07 else ["n/a", "n/a"]
        b = sv["summary"]["by_section"][s] if sv else ["n/a", "n/a"]
        rows.append(f"{names[s]} & {a[0]}/{a[1]} & {b[0]}/{b[1]} \\\\")
    rows.append("\\midrule")
    rows.append(f"Total & {v07['summary']['passed']}/{v07['summary']['total']} & {sv['summary']['passed']}/{sv['summary']['total']} \\\\")
    write("tab_suite.tex", "\n".join(rows) + "\n")
    macro("SuiteTotal", sv["summary"]["total"]); macro("SuitePassNew", sv["summary"]["passed"])
    macro("SuitePassVseven", v07["summary"]["passed"])
    macro("SuiteThrNew", "10^{-5}"); macro("SuiteThrVseven", "10^{-10}")
    macro("SuiteNewPlatform", sv["summary"]["platform"].replace("fpga_sv_", "").replace("_", "\\_"))
    worst = max((r["infidelity"] for r in sv["records"] if r.get("infidelity") is not None), default=None)
    macro("SuiteWorstInfNew", f"{worst:.1e}".replace("e-0", "\\times10^{-").replace("e-", "\\times10^{-") + "}")
    # gate-support categories from the records (gate name = case prefix)
    def gates(d, sec_ok):
        ok, bad = set(), set()
        for r in d["records"]:
            if r["section"] not in ("S1", "S2", "S3"):
                continue
            g = re.sub(r"_(q\d+|\d\d|r)$", "", r["case"])
            (ok if r["passed"] else bad).add(g)
        return ok, bad - ok
    v_ok, v_bad = gates(v07, None); s_ok, s_bad = gates(sv, None)
    macro("VsevenUnsupportedTypes", len(v_bad))
    return dict(v07_ok=sorted(v_ok), v07_bad=sorted(v_bad), sv_ok=sorted(s_ok), sv_bad=sorted(s_bad))


