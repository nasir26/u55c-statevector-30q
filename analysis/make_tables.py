def builds():
    rows = []
    for b in ("sv_e8", "sv_e16", "sv_e16w", "sv_e16w512", "sv_e16w_m4"):
        B = f"{WS}/builds/{b}"
        if not os.path.exists(f"{B}/sv.xclbin"):
            continue
        cfg = open(f"{B}/link.cfg").read()
        ne = int(re.search(r"nk=sv_engine:(\d+)", cfg).group(1))
        ns = int(re.search(r"nk=sv_swap:(\d+)", cfg).group(1)) if "sv_swap" in cfg else 0
        rng = re.search(r"sp=sv_engine_1\.st:HBM\[(\d+)(?::(\d+))?\]", cfg)
        ppe = (int(rng.group(2)) - int(rng.group(1)) + 1) if rng.group(2) else 1
        width = 512 if b.endswith("w512") else 256
        maxh = int(open(f"{B}/maxh.txt").read()) if os.path.exists(f"{B}/maxh.txt") else 2
        clk = re.findall(r"Kernel \(DATA\) clock: ulp_ucs/aclk_kernel_00 = (\d+)", open(f"{WS}/logs/build_{b}.log").read())[-1]
        rpt = open(f"{B}/reports/link/imp/impl_1_kernel_util_placed.rpt").read()
        def row(name):
            m = re.search(r"^\|\s+" + re.escape(name) + r"\s+\|(.*)$", rpt, re.M)
            return [int(x.split("[")[0]) for x in m.group(1).split("|")[:6] if x.strip()]
        eng = [row(f"sv_engine_{i}") for i in range(1, ne + 1)]
        sw = [row(f"sv_swap_{i}") for i in range(1, ns + 1)]
        budget = row("User Budget")
        tot = [sum(c) for c in zip(*(eng + sw))]
        pct = lambda i: 100.0 * tot[i] / budget[i]
        # columns: LUT, LUTAsMem, REG, BRAM, URAM, DSP
        bname = b.replace("_", "\\_")
        rows.append(f"{bname} & {ne} & {ne * ppe} & {width} & {maxh} & {clk} & "
                    f"{tot[0] / 1e3:.0f}k ({pct(0):.0f}\\%) & {tot[3]} ({pct(3):.0f}\\%) & {tot[4]} & {tot[5]} ({pct(5):.0f}\\%) \\\\")
        if b == "sv_e16w_m4":
            macro("FlagClockMHz", clk); macro("FlagLutPct", pct(0), "{:.0f}"); macro("FlagDspPct", pct(5), "{:.0f}")
            macro("FlagEngineLut", eng[0][0] / 1e3, "{:.1f}")
    head = ("\\begin{tabular}{lrrrrrrrrr}\n\\toprule\nBuild & Engines & PCs & AXI bits & $m_\\mathrm{max}$ & MHz & LUT & BRAM & URAM & DSP \\\\\n"
            "\\midrule\n")
    write("tab_builds.tex", head + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


