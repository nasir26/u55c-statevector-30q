def _med_main(fam, n, depth=None):
    out = []
    for f in (f"{RAW}/phase5/sv_main_small_sv_e16w_m4.json", f"{RAW}/phase5/sv_main_large_sv_e16w_m4.json"):
        if os.path.exists(f):
            out += [r for r in json.load(open(f))["records"] if r["family"] == fam and r["n"] == n and not r["warmup"]
                    and (fam != "rqc" or r["depth"] == (depth or 10)) and not r.get("energy_loop")]
    if not out:
        return None
    m = {k: float(np.median([r[k] for r in out])) for k in ("T_kernel", "T_exchange", "T_e2e", "T_h2d", "T_d2h", "T_post", "T_compile")}
    m.update(passes=out[0]["stats"]["n_passes"], ops=out[0]["stats"]["n_ops"], remaps=out[0]["stats"]["n_remaps"], P=out[0]["P"])
    return m


def flagship():
    name = {"ghz": "Ghz", "qft": "Qft", "rqc": "Rqc", "vqe": "Vqe"}
    for fam in ("ghz", "qft", "rqc", "vqe"):
        m = _med_main(fam, 30)
        if m:
            macro(f"Flag{name[fam]}ThirtyEtoE", m["T_e2e"], "{:.1f}")
            macro(f"Flag{name[fam]}ThirtyKernel", m["T_kernel"], "{:.1f}")
            macro(f"Flag{name[fam]}ThirtyExch", m["T_exchange"], "{:.1f}")
            # effective sweep bandwidth: passes x full-state read+write / kernel time
            macro(f"Flag{name[fam]}ThirtySweepBw", m["passes"] * (2 ** 30) * 16 / m["T_kernel"] / 1e9, "{:.0f}")
    # speedup over v07 (T_e2e) at the largest n both ran: 24 for all families, 28 for GHZ
    import csv
    v = {(r["family"], int(r["n"])): float(r["T_e2e_s"]) for r in csv.DictReader(open(f"{WS}/results/processed/v07_baseline.csv"))}
    sp = []
    for fam in ("ghz", "qft", "rqc", "vqe"):
        m = _med_main(fam, 24)
        if m and (fam, 24) in v:
            sp.append(v[(fam, 24)] / m["T_e2e"]); macro(f"SpeedupVseven{name[fam]}TwentyFour", sp[-1], "{:.0f}")
    if sp:
        macro("SpeedupVsevenMin", min(sp), "{:.0f}"); macro("SpeedupVsevenMax", max(sp), "{:.0f}")
    m = _med_main("ghz", 28)
    if m and ("ghz", 28) in v:
        macro("SpeedupVsevenGhzTwentyEight", v[("ghz", 28)] / m["T_e2e"], "{:.0f}")
    # compute roof of the flagship: 16 engines x 4 pairs/cycle x 28 flop x clock
    clk = float(MACROS.get("FlagClockMHz", 300))
    macro("FlagComputeRoof", 16 * 4 * FLOP_PER_PAIR * clk * 1e6 / 1e9, "{:.0f}")


