# ------------------------------------------------------------------ ablations
def _abl(path):
    d = json.load(open(path))["records"]
    out = {}
    for fam in ("ghz", "qft", "rqc", "vqe"):
        rs = [r for r in d if r["family"] == fam and not r["warmup"] and not r.get("energy_loop")]
        if rs:
            out[fam] = dict(k=float(np.median([r["T_kernel"] for r in rs])), x=float(np.median([r["T_exchange"] for r in rs])),
                            e=float(np.median([r["T_e2e"] for r in rs])), passes=rs[0]["stats"]["n_passes"],
                            remaps=rs[0]["stats"]["n_remaps"], ops=rs[0]["stats"]["n_ops"], n=rs[0]["n"], P=rs[0]["P"])
    return out


def ablations():
    flag = f"{RAW}/phase5/sv_ablate_%s_sv_e16w_m4.json"
    e8 = f"{RAW}/phase5/sv_ablate_e8_%s.json"
    tags = ["k12", "k9", "k10", "k11", "nofuse", "notiling", "none", "modulo", "hostswap"]
    def complete(pat):
        return all(os.path.exists(pat % t) and len(_abl(pat % t)) == 4 for t in tags)
    # one source for every row and ratio: the flagship only when its whole ablation set is complete
    pat, src = (flag, "flagship") if complete(flag) else ((e8, "e8") if complete(e8) else (None, None))
    if pat is None:
        return
    def get(tag):
        return _abl(pat % tag), src
    gm = lambda xs: float(np.exp(np.mean(np.log(xs))))
    base, src = get("k12")
    if base is None:
        return
    rows = []
    def ratio(tag, field):
        d, _ = get(tag)
        return gm([d[f][field] / base[f][field] for f in base if f in d]) if d else None
    t = ratio("notiling", "k"); f = ratio("nofuse", "k"); sw = ratio("hostswap", "x")
    if t: macro("AblTilingSpeedup", t, "{:.1f}")
    if f: macro("AblFusionSpeedup", f, "{:.2f}")
    if sw: macro("AblSwapSpeedup", sw, "{:.0f}")
    macro("AblSource", src)
    nt, _ = get("notiling")
    if nt and "rqc" in base and "rqc" in nt:
        macro("AblRqcPasses", base["rqc"]["passes"]); macro("AblRqcPassesNoTiling", nt["rqc"]["passes"])
    labels = [("k12", "default ($k=12$, fusion, tiling, block layout, device exchange)"), ("k9", "tile $k=9$"), ("k10", "tile $k=10$"),
              ("k11", "tile $k=11$"), ("nofuse", "no 1q fusion"), ("notiling", "one gate per pass"), ("none", "no fusion, one gate per pass"),
              ("modulo", "modulo-style initial layout"), ("hostswap", "host-mediated exchange")]
    for tag, lab in labels:
        d, _ = get(tag)
        if not d:
            continue
        cells = " & ".join(f"{d[fm]['k']:.2f} / {d[fm]['x']:.2f} ({d[fm]['passes']})" for fm in ("ghz", "qft", "rqc", "vqe"))
        rows.append(f"{lab} & {cells} \\\\")
    write("tab_ablation.tex", "\n".join(rows) + "\n")
    # CU scaling at n = 24 (e8 build, P = 1..8)
    sc = {pm: _abl(f"{RAW}/phase5/sv_ablate_e8_pmax{pm}_n24.json") for pm in (1, 2, 4, 8)
          if os.path.exists(f"{RAW}/phase5/sv_ablate_e8_pmax{pm}_n24.json")}
    if 1 in sc and 8 in sc:
        macro("CuScaleOneToEight", gm([sc[1][fm]["k"] / sc[8][fm]["k"] for fm in sc[1]]), "{:.1f}")


