def energy():
    num = lambda x: f"{x:.0f}" if x >= 100 else sig3(x)
    e = [r for r in json.load(open(f"{RAW}/phase5/sv_energy_sv_e16w_m4.json"))["records"] if r.get("energy_loop")]
    v = json.load(open(f"{RAW}/phase5/v07_energy.json"))["records"]
    vrun = {(r["family"], r["n"]): r for r in v if not r.get("kind")}
    ws = [r["board_w"] for r in e]
    macro("FlagPowerMin", min(ws), "{:.0f}"); macro("FlagPowerMax", max(ws), "{:.0f}")
    macro("EnergyLoopS", min(r["loop_s"] for r in e), "{:.0f}")
    rows, rat = [], []
    for fam in FAMS:
        for r in sorted([r for r in e if r["family"] == fam], key=lambda r: r["n"]):
            j = r["board_w"] * r["per_run_s"]
            vv = vrun.get((fam, r["n"]))
            vj = vv["board_w"] * vv["per_run_s"] if vv else None
            if vj:
                rat.append(vj / j)
            if r["n"] == 30:
                macro(f"FlagEnergy{FNAME[fam]}Thirty", j, "{:.0f}")
                macro(f"FlagPower{FNAME[fam]}Thirty", r["board_w"], "{:.0f}")
            rows.append(f"{FAM_T[fam] if r['n'] == 20 else ''} & {r['n']} & {num(r['per_run_s'])} & {r['board_w']:.1f} & {num(j)} & "
                        f"{num(j * r['per_run_s'])} & " + (f"{num(vj)} & {vj / j:.0f}" if vj else "n/a & n/a") + " \\\\")
        rows.append("\\addlinespace")
    if rat:
        macro("EnergyVsevenRatioMin", min(rat), "{:.0f}"); macro("EnergyVsevenRatioMax", max(rat), "{:.0f}")
    write("tab_energy.tex", "\n".join(rows[:-1]) + "\n")


