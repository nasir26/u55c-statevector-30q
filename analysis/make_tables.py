"""Write LaTeX table bodies and \\newcommand macros for every number used in the revised text.

Outputs into paper/generated/:
  macros.tex            \\newcommand{\\Num...}{...} for every number quoted in prose
  tab_timing_defs.tex   timing definitions (revision Sec. 6)
  tab_gate_support.tex  four-category gate support (R1.1/R2.3/R4.1), from the fidelity-suite JSONs
  tab_suite.tex         functional-suite results per section, v07 vs new kernel
  tab_hbm.tex           measured HBM ceilings (vendor + hbm1 microbenchmark)
No number is typed by hand: every value is read from results/raw (via analysis/load.py helpers) or computed here.
"""
