MACROS = {}


def macro(name, value, fmt=None):
    assert re.fullmatch(r"[A-Za-z]+", name), name
    MACROS[name] = (fmt.format(value) if fmt else str(value))
    return MACROS[name]


def write(name, body):
    with open(f"{GEN}/{name}", "w") as f:
        f.write("% AUTO-GENERATED by analysis/make_tables.py -- do not edit\n" + body)
    print("wrote", name)


def sigfig(x, n=3):
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return "n/a"
    return f"{x:.{n}g}"


