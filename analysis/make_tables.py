def jitter():
    out, kout = {}, {}
    for tag, f in (("sv", "jitter_sv_sv_e16w_m4.json"), ("vseven", "jitter_v07.json"), ("aer", "jitter_cpu_aer8.json"),
                   ("qulacs", "jitter_cpu_qulacs.json")):
        p = f"{RAW}/phase5/{f}"
        if not os.path.exists(p):
            continue
        for r in json.load(open(p))["records"]:
            x = np.array(r["T_e2e"][r.get("warmup", 0):]) * 1e3
            out[(tag, r["family"], r["n"])] = (np.percentile(x, 50), np.percentile(x, 99), x.max())
            if r.get("T_kernel"):
                k = np.array(r["T_kernel"][r.get("warmup", 0):]) * 1e3
                kout[(tag, r["family"], r["n"])] = (np.percentile(k, 50), np.percentile(k, 99), k.max())
    spread = lambda tag: [(p99 - p50) / p50 for (t, f, n), (p50, p99, mx) in out.items() if t == tag]
    for tag, nm in (("sv", "Sv"), ("vseven", "Vseven"), ("aer", "Aer"), ("qulacs", "Qulacs")):
        s = spread(tag)
        if s:
            macro(f"Jitter{nm}SpreadMin", 100 * min(s), "{:.0f}"); macro(f"Jitter{nm}SpreadMax", 100 * max(s), "{:.0f}")
    for tag, nm in (("sv", "Sv"), ("vseven", "Vseven"), ("aer", "Aer"), ("qulacs", "Qulacs")):
        s = [(p99 - p50) / p50 for (t, f, n), (p50, p99, mx) in kout.items() if t == tag and n >= 12]
        if s:
            macro(f"JitterK{nm}SpreadMin", 100 * min(s), "{:.1f}"); macro(f"JitterK{nm}SpreadMax", 100 * max(s), "{:.1f}")
    if ("sv", "rqc", 16) in out:
        macro("JitterSvRqcSixteenPfifty", out[("sv", "rqc", 16)][0], "{:.1f}")
        macro("JitterSvRqcSixteenPnn", out[("sv", "rqc", 16)][1], "{:.1f}")
    import csv
    os.makedirs(f"{WS}/results/processed", exist_ok=True)
    with open(f"{WS}/results/processed/jitter_summary.csv", "w") as fh:
        w = csv.writer(fh); w.writerow(["platform", "family", "n", "p50_ms", "p99_ms", "max_ms", "k_p50_ms", "k_p99_ms", "k_max_ms"])
        for key, vals in sorted(out.items()):
            w.writerow(list(key) + [f"{x:.4f}" for x in vals + kout.get(key, (np.nan,) * 3)])



