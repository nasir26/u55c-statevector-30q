NWORD = {4: "Four", 20: "Twenty", 24: "TwentyFour", 26: "TwentySix", 28: "TwentyEight", 30: "Thirty"}
GPU_HOST = os.environ.get("GPU_HOST_TAG", "a100")
GPU_ALL = ("aer_gpu single cusv=1", "aer_gpu double cusv=1", "cudaq single", "cudaq double")
GPU_COLS = ("aer_gpu single cusv=1", "aer_gpu double cusv=1", "cudaq single")   # columns of Table xplat


def _xplat_frames():
    df = load_runs()
    df = df[(df.depth.isna()) | (df.depth == 10)]
    fl = summarise(df[df.source.str.contains(r"sv_main_.*sv_e16w_m4", regex=True)])
    cpu = summarise(df[df.platform.str.startswith("cpu") & (df.platform != "cpu_numpy1t")])
    gpu = summarise(df[df.platform.str.startswith("gpu") & df.config.str.contains(f"[{GPU_HOST}]", regex=False)])
    return fl, cpu, gpu


def sig3(x):
    return "n/a" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:#.3g}".rstrip(".")


def xplat():
    fl, cpu, gpu = _xplat_frames()
    t = json.load(open(f"{RAW}/phase5/cpu_triad_128c_interleave.json"))
    macro("CpuTriad", t["triad_gbps"], "{:.0f}")
    get = lambda d, fam, n, col="T_e2e": (lambda x: float(x.iloc[0]) if len(x) else None)(d[(d.family == fam) & (d.n == n)][col])
    best = cpu.loc[cpu.groupby(["family", "n"]).T_e2e.idxmin()]
    ratios30, cross = [], {}
    for fam in FAMS:
        for n in (24, 28, 30):
            b = best[(best.family == fam) & (best.n == n)]
            f = get(fl, fam, n)
            if len(b) and f:
                r = float(b.T_e2e.iloc[0]) / f
                macro(f"XplatRatio{FNAME[fam]}{NWORD[n]}", r, "{:.2f}")
                macro(f"XplatBestCpu{FNAME[fam]}{NWORD[n]}", CPU_LABEL.get(b.config.iloc[0], b.config.iloc[0]))
                macro(f"XplatBestCpuT{FNAME[fam]}{NWORD[n]}", float(b.T_e2e.iloc[0]), "{:.1f}" if n >= 28 else "{:.2f}")
                if n == 30:
                    ratios30.append(r)
        # smallest n from which the FPGA is faster than the best CPU configuration at every larger measured n
        ns = sorted(set(fl[fl.family == fam].n) & set(best[best.family == fam].n))
        win = [n for n in ns if get(fl, fam, n) < float(best[(best.family == fam) & (best.n == n)].T_e2e.iloc[0])]
        tail = [n for n in ns if all(m in win for m in ns if m >= n)]
        cross[fam] = min(tail) if tail else None
    r24 = [float(best[(best.family == f) & (best.n == 24)].T_e2e.iloc[0]) / get(fl, f, 24) for f in FAMS]
    macro("XplatRatioTwentyFourMin", min(r24), "{:.2f}"); macro("XplatRatioTwentyFourMax", max(r24), "{:.2f}")
    # against Aer fp32 with fusion (the usual default) at n = 30
    aer = cpu[cpu.config == "aer 128t single fusion=1"]
    wins = []
    for fam in FAMS:
        a, f = get(aer, fam, 30), get(fl, fam, 30)
        if a and f:
            macro(f"XplatAerRatio{FNAME[fam]}Thirty", a / f, "{:.2f}")
    # share of the FPGA T_e2e at n = 30 spent in state return and sampling (work the CPU runs do not do)
    for fam in FAMS:
        m = _med_main(fam, 30)
        if m:
            macro(f"FlagDtwoh{FNAME[fam]}Thirty", m["T_d2h"], "{:.1f}"); macro(f"FlagPost{FNAME[fam]}Thirty", m["T_post"], "{:.2f}")
    oth = [float(best[(best.family == f) & (best.n == 30)].T_e2e.iloc[0]) / get(fl, f, 30) for f in ("qft", "rqc", "vqe")]
    macro("XplatRatioOtherThirtyMin", min(oth), "{:.2f}"); macro("XplatRatioOtherThirtyMax", max(oth), "{:.2f}")
    macro("XplatCpuFasterOtherThirtyMin", 1 / max(oth), "{:.2f}"); macro("XplatCpuFasterOtherThirtyMax", 1 / min(oth), "{:.2f}")
    if ratios30:
        macro("XplatRatioThirtyMin", min(ratios30), "{:.2f}"); macro("XplatRatioThirtyMax", max(ratios30), "{:.2f}")
    if cross.get("ghz"):
        macro("XplatGhzCrossN", cross["ghz"])
    macro("XplatOtherWinsN", sum(1 for f in ("qft", "rqc", "vqe") if cross.get(f)))
    # fixed overhead at small n: FPGA e2e vs fastest CPU at n = 4 (milliseconds / microseconds)
    macro("XplatFpgaSmallMs", float(np.median([get(fl, f, 4) for f in FAMS])) * 1e3, "{:.1f}")
    macro("XplatCpuSmallUs", float(np.median([float(best[(best.family == f) & (best.n == 4)].T_e2e.iloc[0]) for f in FAMS])) * 1e6, "{:.0f}")
    # table: n = 24, 28, 30; FPGA kernel and e2e, CPU configurations (e2e), GPU (e2e) when measured
    cols = ["aer 128t single fusion=1", "aer 128t double fusion=1", "qsim 128t", "qulacs 128t"]
    gcfg = [c for c in GPU_ALL if not gpu.empty and gpu.config.str.startswith(c).any()]
    macro("XplatGpuCols", len(GPU_COLS))
    rows = []
    for fam in FAMS:
        for n in (24, 28, 30):
            cells = [sig3(get(fl, fam, n, "T_kernel")), sig3(get(fl, fam, n))]
            for c in cols:
                cells.append(sig3(get(cpu[cpu.config == c], fam, n)))
            bt = best[(best.family == fam) & (best.n == n)].T_e2e
            cells.append(f"{float(bt.iloc[0]) / get(fl, fam, n):.2f}" if len(bt) and get(fl, fam, n) else "n/a")
            for c in GPU_COLS:                      # GPU configurations that completed on the A100
                cells.append(sig3(get(gpu[gpu.config.str.startswith(c)], fam, n)))
            rows.append(f"{FAM_T[fam] if n == 24 else ''} & {n} & " + " & ".join(cells) + " \\\\")
        rows.append("\\addlinespace")
    write("tab_xplat.tex", "\n".join(rows[:-1]) + "\n")
    # GPU (A100, Aer fp32 with cuStateVec, measured on a different host): ratios to the FPGA, widest size, power, energy
    g1 = gpu[gpu.config.str.startswith("aer_gpu single cusv=1")] if not gpu.empty else gpu
    if not g1.empty:
        macro("GpuMaxN", int(g1.n.max()))
        gr = []
        for fam in FAMS:
            for n in (24, 28, 30):
                gt, f = get(g1, fam, n), get(fl, fam, n)
                if gt and f:
                    macro(f"XplatGpuRatio{FNAME[fam]}{NWORD[n]}", f / gt, "{:.2f}")    # > 1: GPU faster
                    macro(f"XplatGpuT{FNAME[fam]}{NWORD[n]}", gt, "{:.2f}")
                    if n == 30:
                        gr.append(f / gt)
        if gr:
            macro("XplatGpuRatioThirtyMin", min(gr), "{:.2f}"); macro("XplatGpuRatioThirtyMax", max(gr), "{:.2f}")
        # GPU against the best CPU configuration at n = 30
        gc = [float(best[(best.family == f) & (best.n == 30)].T_e2e.iloc[0]) / get(g1, f, 30) for f in FAMS if get(g1, f, 30)]
        if gc:
            macro("XplatGpuOverCpuThirtyMin", min(gc), "{:.1f}"); macro("XplatGpuOverCpuThirtyMax", max(gc), "{:.1f}")
        g0 = gpu[gpu.config.str.startswith("aer_gpu single cusv=0")]
        for fam in ("ghz", "qft"):
            a1, a0 = get(g1, fam, 30), get(g0, fam, 30)
            if a1 and a0:
                macro(f"GpuCusvGain{FNAME[fam]}Thirty", a0 / a1, "{:.2f}")
        # board power and energy per run from the nvidia-smi samples of each run window (>= 50 samples at n = 30)
        raw = [json.loads(l) for l in open(f"{RAW}/gpu/{GPU_HOST}_aer_single_cusv.jsonl")]
        raw = [r for r in raw if not r.get("error") and not r["warmup"] and r.get("power")]
        pw, ej, nr = [], {}, []
        for fam in FAMS:
            rr = [r for r in raw if r["family"] == fam and r["n"] == 30]
            if rr:
                P = float(np.median([r["power"]["mean_w"] for r in rr])); J = float(np.median([r["power"]["mean_w"] * r["wall_s"] for r in rr]))
                pw.append(P); ej[fam] = J; nr += [r["power"]["n"] for r in rr]
                macro(f"GpuEnergy{FNAME[fam]}Thirty", J, "{:.0f}"); macro(f"GpuPower{FNAME[fam]}Thirty", P, "{:.0f}")
        # other GPU configurations: largest width with a result and the time at n = 30 per family
        for c, key in (("aer_gpu double cusv=1", "AerDouble"), ("cudaq single", "CudaqSingle"), ("cudaq double", "CudaqDouble")):
            gc_ = gpu[gpu.config.str.startswith(c)]
            if gc_.empty:
                continue
            macro(f"Gpu{key}MaxN", int(gc_.n.max()))
            for fam in FAMS:
                t = get(gc_, fam, 30)
